    // 엘리먼트 생성 헬퍼: h('div', {class:'x', onclick:fn, text:'...'}, [children])
    function h(tag, attrs, children) {
        const el = document.createElement(tag);
        if (attrs) {
            for (const k in attrs) {
                const v = attrs[k];
                if (v == null || v === false) continue;
                if (k === "class") el.className = v;
                else if (k === "text") el.textContent = v;
                else if (k === "html") throw new Error("HTML 속성은 XSS 방지를 위해 지원하지 않는다. 마크다운 파이프라인을 사용한다.");
                else if (k.slice(0, 2) === "on") el.addEventListener(k.slice(2), v);
                else if (k === "dataset") Object.assign(el.dataset, v);
                else if (k === "style") el.style.cssText = v;
                else el.setAttribute(k, v === true ? "" : v);
            }
        }
        if (children)
            for (const c of children) {
                if (c == null || c === false) continue;
                el.append(c);
            }
        return el;
    }

    // 스프라이트 아이콘: icon('copy')는 <svg class="icon"><use href="#i-copy"/></svg>를 만든다.
    const SVG_NS = "http://www.w3.org/2000/svg";
    function icon(name, extraClass) {
        const svg = document.createElementNS(SVG_NS, "svg");
        svg.setAttribute("class", "icon" + (extraClass ? " " + extraClass : ""));
        svg.setAttribute("aria-hidden", "true");
        const use = document.createElementNS(SVG_NS, "use");
        use.setAttribute("href", "#i-" + name);
        svg.appendChild(use);
        return svg;
    }

    // 클립보드 복사(file:// 폴백 포함). 성공 여부 반환.
    function copyText(text) {
        try {
            if (navigator.clipboard && window.isSecureContext !== false) {
                return navigator.clipboard.writeText(text).then(
                    () => true,
                    () => fallbackCopy(text),
                );
            }
        } catch (_) {
            /* 폴백으로 진행 */
        }
        return Promise.resolve(fallbackCopy(text));
    }
    function fallbackCopy(text) {
        try {
            const ta = document.createElement("textarea");
            ta.value = text;
            ta.style.cssText = "position:fixed;opacity:0";
            document.body.appendChild(ta);
            ta.select();
            const ok = document.execCommand("copy");
            ta.remove();
            return ok;
        } catch (_) {
            return false;
        }
    }

